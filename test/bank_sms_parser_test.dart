// تست‌های parseBankSms - تشخیص واریز/برداشت و مبلغ از متن پیامک بانکی.
// این تابع تا پیش از این هیچ تست خودکاری نداشت؛ چون پیام‌های بانکی واقعی
// در قالب و چیدمان بسیار متنوعند، این تست‌ها سناریوهای اصلی (واریز/برداشت،
// واحد ریال/تومان، جداکننده هزارگان، نویسه عربی، نبود شواهد بانکی، مبلغ صفر،
// و انتخاب نزدیک‌ترین عدد به کلیدواژه تراکنش نه هر عددی در پیام) را پوشش می‌دهند.
import 'package:flutter_test/flutter_test.dart';

import 'package:daftaryar/services/bank_sms_parser.dart';

void main() {
  group('parseBankSms — تشخیص واریز', () {
    test('واریز با واحد ریال - مبلغ به تومان تبدیل می‌شود (تقسیم بر ۱۰)', () {
      final r = parseBankSms('به حساب شما 150,000 ریال واریز شد');
      expect(r, isNotNull);
      expect(r!.type, 'دریافت');
      expect(r.amount, 15000);
    });

    test('واریز با واحد تومان - مبلغ دست‌نخورده می‌ماند', () {
      final r = parseBankSms('به کارت شما 2000000 تومان واریز شد');
      expect(r, isNotNull);
      expect(r!.type, 'دریافت');
      expect(r.amount, 2000000);
    });
  });

  group('parseBankSms — تشخیص برداشت/هزینه', () {
    test('خرید از حساب - نوع پرداخت و تبدیل ریال به تومان', () {
      final r = parseBankSms('خرید از فروشگاه به مبلغ 50,000 ریال از حساب شما کسر شد');
      expect(r, isNotNull);
      expect(r!.type, 'پرداخت');
      expect(r.amount, 5000);
    });

    test('کارمزد بانکی هم به‌عنوان پرداخت شناسایی می‌شود', () {
      final r = parseBankSms('کارمزد 5,000 ریال از کارت شما کسر شد');
      expect(r, isNotNull);
      expect(r!.type, 'پرداخت');
    });
  });

  group('parseBankSms — رد پیام‌های نامرتبط', () {
    test('بدون هیچ شاهدی بر بانکی‌بودن پیام (ریال/تومان/حساب/کارت/مانده/موجودی)، null برمی‌گرداند', () {
      final r = parseBankSms('واریز حقوق شما توسط شرکت انجام و تسویه گردید');
      expect(r, isNull);
    });

    test('بدون هیچ کلیدواژه تراکنشی، null برمی‌گرداند', () {
      final r = parseBankSms('قبض برق شما برای این ماه صادر شد، مبلغ 120,000 تومان');
      expect(r, isNull);
    });

    test('مبلغ صفر معتبر شناخته نمی‌شود', () {
      final r = parseBankSms('واریز 0000 ریال به حساب شما انجام شد');
      expect(r, isNull);
    });
  });

  group('parseBankSms — نویسه‌های عربی', () {
    test('ي و ك عربی در متن پیامک، مثل معادل فارسی (ی/ک) پردازش می‌شوند', () {
      final r = parseBankSms('به كارت شما 100,000 تومان واريز شد');
      expect(r, isNotNull);
      expect(r!.type, 'دریافت');
      expect(r.amount, 100000);
    });
  });

  group('parseBankSms — انتخاب عدد درست وقتی چند عدد در پیام هست', () {
    test('عدد بعد از کلیدواژه تراکنش انتخاب می‌شود، نه مانده حساب قبل از آن', () {
      final r = parseBankSms('موجودی فعلی 900,000 تومان. واریز 300,000 تومان به حساب شما');
      expect(r, isNotNull);
      expect(r!.amount, 300000, reason: 'نباید مانده حساب (900,000) را با مبلغ تراکنش اشتباه بگیرد');
    });
  });
}
